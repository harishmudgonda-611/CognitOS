from pathlib import Path

from cognit.builder.filesystem import FileSystem


class WebsiteBuilder:

    def __init__(self):
        self.fs = FileSystem()

    def build(self, name: str = "website"):

        root = Path("output") / name.lower()

        self.fs.ensure_directory(root)

        self.fs.write_file(
            root / "index.html",
            """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>CognitOS Website</title>
<link rel="stylesheet" href="style.css">
</head>
<body>

<header>
<h1>Welcome to CognitOS</h1>
<p>Your first generated website.</p>
</header>

<script src="script.js"></script>

</body>
</html>
"""
        )

        self.fs.write_file(
            root / "style.css",
            """body{
font-family:Arial,sans-serif;
margin:40px;
background:#f4f4f4;
}
h1{
color:#2563eb;
}
"""
        )

        self.fs.write_file(
            root / "script.js",
            """console.log("Website generated by CognitOS");"""
        )

        return [
            str(root / "index.html"),
            str(root / "style.css"),
            str(root / "script.js"),
        ]
        
